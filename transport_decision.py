# Програма: Вибір транспорту
# Автор: [Твоє ім'я]
# Опис: Програма радить користувачу оптимальний вид транспорту залежно від відстані до місця призначення.

print("=== ВИБІР ТРАНСПОРТУ ===")
print("Ця програма допоможе вам обрати найзручніший спосіб пересування.\n")

# Введення даних користувачем
try:
    distance = float(input("Введіть відстань до місця призначення (у км): "))

    # Перевірка правильності введення
    if distance < 0:
        print("Помилка: відстань не може бути від’ємною.")
    elif distance < 2:
        print("Радимо піти пішки. Це найзручніше на короткі відстані.")
    elif 2 <= distance <= 20:
        has_bike = input("Чи маєте велосипед? (так/ні): ").strip().lower()
        if has_bike == "так":
            print("Радимо їхати велосипедом.")
        elif has_bike == "ні":
            print("Радимо скористатись автобусом.")
        else:
            print("Невірна відповідь. Припустимо, що велосипеда немає — радимо автобус.")
    else:
        print("Радимо їхати автомобілем. Це оптимальний варіант на великі відстані.")

    print("\nДякуємо за користування програмою 'Вибір транспорту'.")
    print("Бажаємо гарної подорожі!")

except ValueError:
    print("Помилка: потрібно ввести числове значення відстані.")
